// Bundles supabase/migrations/*.sql into the app so it can update its own
// database on start-up (src/lib/migrations.generated.ts). Runs before every build.
import fs from "node:fs";
const dir = new URL("../supabase/migrations/", import.meta.url);
const files = fs.readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const out = `// GENERATED by scripts/gen-migrations.mjs from supabase/migrations. Do not edit.\nexport const MIGRATIONS: { id: string; sql: string }[] = [\n${files
  .map((f) => `  { id: ${JSON.stringify(f.replace(/\.sql$/, ""))}, sql: ${JSON.stringify(fs.readFileSync(new URL(f, dir), "utf8"))} },`)
  .join("\n")}\n];\n`;
fs.writeFileSync(new URL("../src/lib/migrations.generated.ts", import.meta.url), out);
console.log(`Bundled ${files.length} migrations`);
